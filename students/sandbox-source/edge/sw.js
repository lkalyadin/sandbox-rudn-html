// Свой service worker для стенда студентов.
//
// ЗАЧЕМ. UI OpenCode (веб-приложение на SolidJS) ставит свой service worker
// на весь origin (/sw.js). Он работает через workbox: на ЛЮБУЮ навигацию
// (переход по адресу, клик по ссылке) отдаёт заранее закэшированную
// оболочку приложения /index.html — кроме путей из deny-листа
// (/api/, /auth/, /_assets/, /assets/).
//
// Из-за этого открыть результат работы агента по ссылке
// https://<ip>/files/output/<файл> было невозможно: браузер вообще не
// спрашивал сервер, а показывал UI OpenCode, который на неизвестном маршруте
// падал с «Error: Unrecognised route!». Файл был на сервере, но браузер его
// не видел.
//
// Что делаем. Отдаём свой service worker: он ничего не кэширует и не
// перехватывает запросы — всё идёт в сеть как обычно. Для стенда, где
// сервер всегда под рукой, офлайн-режим не нужен, а вот доступ к файлам
// результата — нужен.
//
// Если OpenCode обновится и его штатный sw.js вернётся — симптом вернётся.
// Тогда нужно либо поправить deny-лист в его sw.js, либо вернуть этот файл.

self.addEventListener("install", () => {
  // Забираем управление сразу, не дожидаясь закрытия всех вкладок.
  self.skipWaiting();
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    (async () => {
      // Выкидываем кэши штатного workbox: в них лежит та самая оболочка
      // /index.html, из-за которой был сломан доступ к файлам результата.
      const keys = await caches.keys();
      await Promise.all(
        keys
          .filter((k) => k.includes("precache") || k.includes("workbox"))
          .map((k) => caches.delete(k))
      );
      await self.clients.claim();
    })()
  );
});

// Никакого respondWith: браузер сам идёт в сеть. Навигация к /files/... и
// к самому UI работают одинаково — как обычные запросы.
self.addEventListener("fetch", () => {});
